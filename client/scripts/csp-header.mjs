#!/usr/bin/env node
/**
 * Write the nginx Content-Security-Policy header for the built portals.
 *
 *   node scripts/csp-header.mjs <out.conf> <built.html>...
 *
 * The two portals carry small inline scripts in index.html (the theme applied
 * before first paint, the stale-cache clean-up). A policy without
 * 'unsafe-inline' must name each by its SHA-256, and the hash has to come from
 * the BUILT file: hashing the source by hand breaks the moment either script
 * is edited, and the page then silently loses dark mode. Run at image build
 * time, so the header always matches the files it serves.
 *
 * The telehealth video origin is not known at build time; the placeholders are
 * filled when the container starts (nginx/40-csp-telehealth.sh).
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [out, ...pages] = process.argv.slice(2);
if (!out || pages.length === 0) {
  console.error('usage: csp-header.mjs <out.conf> <built.html>...');
  process.exit(2);
}

const hashes = new Set();
for (const page of pages) {
  const html = readFileSync(page, 'utf8');
  // Inline scripts only: a <script src=...> is covered by 'self'.
  for (const match of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)) {
    if (match[1].trim() === '') continue;
    hashes.add(`'sha256-${createHash('sha256').update(match[1], 'utf8').digest('base64')}'`);
  }
}

const policy = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].join(' ')} __TELEHEALTH_HTTPS__`,
  // React sets style attributes; Tailwind ships a stylesheet. Google Fonts CSS.
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' data: https://fonts.gstatic.com",
  "img-src 'self' data: blob:",
  "media-src 'self' blob:",
  // The API and SSE are same-origin; push registration talks to Google.
  "connect-src 'self' https://fcmregistrations.googleapis.com https://firebaseinstallations.googleapis.com __TELEHEALTH_HTTPS__ __TELEHEALTH_WSS__",
  // Document previews are blob: frames; video visits frame the Jitsi origin.
  "frame-src 'self' blob: __TELEHEALTH_HTTPS__",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

writeFileSync(
  out,
  `# Generated by client/scripts/csp-header.mjs at image build time. Do not edit.\n` +
    `add_header Content-Security-Policy "${policy}" always;\n`
);
console.log(`CSP written to ${out} with ${hashes.size} inline-script hash(es)`);
